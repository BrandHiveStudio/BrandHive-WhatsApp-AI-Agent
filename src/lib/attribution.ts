import type { Message } from "@/lib/types";

export type MessageSenderCategory =
  | "customer"
  | "ai"
  | "staff_dashboard"
  | "staff_wa_app"
  | "unattributed_outbound";

export interface MessageAttribution {
  category: MessageSenderCategory;
  badgeLabel: string;
  badgeIcon: string;
  badgeStyle: "ai" | "staff" | "coexistence" | "neutral" | "none";
  authorName: string | null;
  isHuman: boolean | null;
  isReliable: boolean;
  description: string;
}

/**
 * Pure, reliable message sender attribution classifier.
 *
 * Rules:
 * 1. Customer messages: role === 'user'. Always 100% human, 100% reliable.
 * 2. WhatsApp Business App messages (SMB Coexistence):
 *    - Explicitly set sender_type === 'staff_wa_app', OR
 *    - role === 'assistant' AND Boolean(whatsapp_msg_id) AND ai_reply_sent === true.
 *    - 100% reliable from Meta coexistence webhook echo.
 * 3. Staff Dashboard messages:
 *    - Explicitly set sender_type === 'staff_dashboard', OR
 *    - role === 'assistant' AND Boolean(whatsapp_msg_id) AND ai_reply_sent === false.
 *    - 100% reliable when sent via authenticated staff dashboard route.
 * 4. Explicit AI-generated replies:
 *    - Explicitly set sender_type === 'ai'.
 * 5. Unattributed / Historical outbound messages:
 *    - Outbound assistant messages whose authorship cannot be proven from reliable records.
 *    - Labeled neutrally as 'BrandHive Team' without false certainty or guessing.
 */
export function getMessageAttribution(
  msg: Partial<Message> | null | undefined
): MessageAttribution {
  if (!msg) {
    return {
      category: "unattributed_outbound",
      badgeLabel: "BrandHive Team",
      badgeIcon: "🏢",
      badgeStyle: "neutral",
      authorName: null,
      isHuman: null,
      isReliable: false,
      description: "Sender record unavailable",
    };
  }

  // 1. Customer Message
  if (msg.role === "user") {
    return {
      category: "customer",
      badgeLabel: "",
      badgeIcon: "",
      badgeStyle: "none",
      authorName: null,
      isHuman: true,
      isReliable: true,
      description: "Customer inbound message via WhatsApp",
    };
  }

  // Explicit sender_type if recorded in database
  if (msg.sender_type === "staff_dashboard") {
    return {
      category: "staff_dashboard",
      badgeLabel: msg.sender_name ? `Staff: ${msg.sender_name}` : "Staff (Dashboard)",
      badgeIcon: "👤",
      badgeStyle: "staff",
      authorName: msg.sender_name || null,
      isHuman: true,
      isReliable: true,
      description: "Sent by staff member from BrandHive web dashboard",
    };
  }

  if (msg.sender_type === "staff_wa_app") {
    return {
      category: "staff_wa_app",
      badgeLabel: "WhatsApp Business App",
      badgeIcon: "📱",
      badgeStyle: "coexistence",
      authorName: msg.sender_name || "WhatsApp Business App",
      isHuman: true,
      isReliable: true,
      description: "Sent by human staff from physical WhatsApp Business app or linked web",
    };
  }

  if (msg.sender_type === "ai") {
    return {
      category: "ai",
      badgeLabel: "BrandHive AI",
      badgeIcon: "🤖",
      badgeStyle: "ai",
      authorName: "BrandHive AI",
      isHuman: false,
      isReliable: true,
      description: "Automated response generated by Gemini AI",
    };
  }

  // 2. WhatsApp Business App Coexistence Echo (verified webhook echo signature)
  // When an echo arrives from Meta SMB coexistence, it is stored with:
  // role: 'assistant', direction: 'out', whatsapp_msg_id: <wamid>, ai_reply_sent: true
  if (msg.role === "assistant" && Boolean(msg.whatsapp_msg_id) && msg.ai_reply_sent === true) {
    return {
      category: "staff_wa_app",
      badgeLabel: "WhatsApp Business App",
      badgeIcon: "📱",
      badgeStyle: "coexistence",
      authorName: "WhatsApp Business App",
      isHuman: true,
      isReliable: true,
      description: "Sent by human staff from physical WhatsApp Business app or linked web",
    };
  }

  // 3. Staff Dashboard Message (sent through authenticated dashboard API with stored outbound wamid)
  if (msg.role === "assistant" && Boolean(msg.whatsapp_msg_id) && msg.ai_reply_sent === false) {
    return {
      category: "staff_dashboard",
      badgeLabel: msg.sender_name ? `Staff: ${msg.sender_name}` : "Staff (Dashboard)",
      badgeIcon: "👤",
      badgeStyle: "staff",
      authorName: msg.sender_name || null,
      isHuman: true,
      isReliable: true,
      description: "Sent by staff member from BrandHive web dashboard",
    };
  }

  // 4. Unattributed / Historical Outbound Message
  // For assistant messages whose authorship cannot be proven from reliable persisted records
  // (e.g. missing WhatsApp ID or unverified origin), display neutral BrandHive Team attribution without guessing.
  return {
    category: "unattributed_outbound",
    badgeLabel: "BrandHive Team",
    badgeIcon: "🏢",
    badgeStyle: "neutral",
    authorName: null,
    isHuman: null,
    isReliable: false,
    description: "Outbound message; specific author record unavailable",
  };
}
